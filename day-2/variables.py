# Day 2: Python Variables and Data Types

# Variables
name = "John"
age = 21
height = 5.8
is_student = True

# Display variables
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Display data types
print("\nData Types:")
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
